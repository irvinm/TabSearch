<#
.SYNOPSIS
  Generates config.js, the self-contained Firefox Autoconfig file.

.DESCRIPTION
  Autoconfig runs in a privileged sandbox and, in current Firefox versions,
  refuses to load arbitrary file:// subscripts as untrusted. To keep the
  integration self-contained, this script combines the readable source
  (tabsearch-native-tabs.js) with the small initializer into config.js.

  install.ps1 copies config.js to <Firefox>\tabsearch-autoconfig.cfg.
#>
$ErrorActionPreference = "Stop"
$scriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$sourcePath = Join-Path $scriptDir "tabsearch-native-tabs.js"
$outputPath = Join-Path $scriptDir "config.js"

if (-not (Test-Path $sourcePath)) {
  throw "Missing source file: $sourcePath"
}

$source = [System.IO.File]::ReadAllText($sourcePath)
$header = @'
// TabSearch Autoconfig loader (Firefox browser chrome)
// Generated by build-config.ps1 from tabsearch-native-tabs.js.
// Installed as tabsearch-autoconfig.cfg in the Firefox application directory.
// No remote code, no eval, and no Firefox preference changes at runtime.
(function () {
  "use strict";

  // Autoconfig runs in Firefox's privileged sandbox where Services is already
  // available as a global. Importing it again fails on current builds.

'@
$footer = @'


  TabSearchNativeTabs.init();
})();
'@

$content = $header + "`r`n" + $source + $footer
$utf8NoBom = New-Object System.Text.UTF8Encoding($false)
[System.IO.File]::WriteAllText($outputPath, $content, $utf8NoBom)
Write-Host "Generated: $outputPath"
